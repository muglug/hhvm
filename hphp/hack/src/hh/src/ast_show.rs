//! Port of the `[@@deriving show]` printers of `ast/ast_defs.ml` and
//! `annotated_ast/aast_defs.ml`: the `pp_*` functions that ppx_deriving's
//! `show` plugin writes for the types of `Ast_defs` and `Aast_defs`
//! (`Aast.pp_program` is `Aast_defs.pp_program`), over the
//! `oxidized` types, laid out with [`crate::format`] (OCaml's `Format`): with
//! the same calls, the output is OCaml's, line breaks included. See
//! `hh/PORTING.md`.
//!
//! The modules [`ast_defs`] and [`aast_defs`] are generated by
//! `ast_show_gen.py` (next to this file) from the OCaml type declarations
//! (preprocessed: the generator applies the rules of `ppx_deriving_show.ml`:
//! `with_path`, `[@opaque]`, the builtin printers of `list`, `option`,
//! `string`, ...) and from the `oxidized` declarations, matched constructor
//! by constructor and field by field. Do not edit them by hand: regenerate
//! (the command is in the generator's header) and replace everything after
//! the generated-code marker line.
//!
//! The printers of the types of other modules that the AST contains are here,
//! by hand: `Pos.pp`, `Local_id.pp`, `File_info.pp_mode` (the hand-written one
//! that shadows the derived one), `Namespace_env.pp_env` (derived, 7 fields).
//!
//! The polymorphic printers of OCaml (`pp_expr poly_ex poly_en fmt e`) take
//! the printers of the annotations; here they are in [`P`], with the
//! formatter.

use crate::format;
use crate::format::Formatter;
use crate::rt::ocaml_printf::sprintf_s_bytes;

/// The formatter and the printers of the annotations (`poly_ex`,
/// `poly_en`) that every printer passes on.
pub struct P<'a, Ex, En> {
    pub fmt: &'a mut Formatter,
    pub ex: &'a dyn Fn(&mut Formatter, &Ex),
    pub en: &'a dyn Fn(&mut Formatter, &En),
    /// Every `pos` prints as `Pos.none`: the printers of
    /// `print_*_without_position`, which print the AST after an `Aast.map`
    /// whose `on_pos` returns `Pos.none`. (The annotations are printed by
    /// `ex`, which is given the annotation unchanged, as `on_'ex` is.)
    pub pos_none: bool,
}

impl<'a, Ex, En> P<'a, Ex, En> {
    pub fn new(
        fmt: &'a mut Formatter,
        ex: &'a dyn Fn(&mut Formatter, &Ex),
        en: &'a dyn Fn(&mut Formatter, &En),
    ) -> Self {
        P {
            fmt,
            ex,
            en,
            pos_none: false,
        }
    }
}

// The pieces of the format strings of the derived printers
// (`Format.fprintf fmt "(@["` is `(` then `@[`, ...).

fn ps<Ex, En>(p: &mut P<'_, Ex, En>, s: &str) {
    format::pp_print_string(p.fmt, s)
}

/// `@[<n>`
fn open_box<Ex, En>(p: &mut P<'_, Ex, En>, indent: isize) {
    format::pp_open_box(p.fmt, indent)
}

/// `@]`
fn close_box<Ex, En>(p: &mut P<'_, Ex, En>) {
    format::pp_close_box(p.fmt)
}

/// `@ `
fn space<Ex, En>(p: &mut P<'_, Ex, En>) {
    format::pp_print_space(p.fmt)
}

/// `@,`
fn cut<Ex, En>(p: &mut P<'_, Ex, En>) {
    format::pp_print_cut(p.fmt)
}

/// `"(@["`, the start of a tuple.
fn fprintf_open_tuple<Ex, En>(p: &mut P<'_, Ex, En>) {
    ps(p, "(");
    open_box(p, 0);
}

/// `"@])"`, the end of a tuple.
fn fprintf_close_tuple<Ex, En>(p: &mut P<'_, Ex, En>) {
    close_box(p);
    ps(p, ")");
}

/// `",@ "`
fn comma_space<Ex, En>(p: &mut P<'_, Ex, En>) {
    ps(p, ",");
    space(p);
}

/// `";@ "`
fn semi_space<Ex, En>(p: &mut P<'_, Ex, En>) {
    ps(p, ";");
    space(p);
}

/// `"@[<2>["`, the start of a list.
fn list_open<Ex, En>(p: &mut P<'_, Ex, En>) {
    open_box(p, 2);
    ps(p, "[");
}

/// `"@,]@]"`, the end of a list.
fn list_close<Ex, En>(p: &mut P<'_, Ex, En>) {
    cut(p);
    ps(p, "]");
    close_box(p);
}

/// `"@[%s =@ "` of a record field.
fn field_open<Ex, En>(p: &mut P<'_, Ex, En>, name: &str) {
    open_box(p, 0);
    ps(p, name);
    ps(p, " =");
    space(p);
}

/// `%d`
fn pp_int<Ex, En>(p: &mut P<'_, Ex, En>, i: isize) {
    ps(p, &i.to_string())
}

/// `%B`
fn pp_bool<Ex, En>(p: &mut P<'_, Ex, En>, b: bool) {
    ps(p, if b { "true" } else { "false" })
}

/// `%S` (of the bytes of a `String`, a `BString` or a `Vec<u8>`)
fn pp_string<Ex, En>(p: &mut P<'_, Ex, En>, s: &(impl AsRef<[u8]> + ?Sized)) {
    ps(p, &sprintf_s_bytes(s.as_ref()))
}

/// `Pos.pp`: `[Pos.none]`, or `[line:col-col]` (one line) or
/// `[line:col-line:col]`, the columns counted from 1, the end one past the
/// last character.
pub fn pp_pos_t<Ex, En>(p: &mut P<'_, Ex, En>, pos: &oxidized::pos::Pos) {
    if p.pos_none || crate::pos::equal_none(pos) {
        ps(p, "[Pos.none]")
    } else {
        let ((l1, b1, o1), (l2, b2, o2)) = pos.to_start_and_end_lnum_bol_offset();
        ps(p, "[");
        // `File_pos_*.pp`: the line, ":", the column plus one.
        pp_int(p, l1 as isize);
        ps(p, ":");
        pp_int(p, o1 as isize - b1 as isize + 1);
        ps(p, "-");
        if l1 == l2 {
            pp_int(p, o2 as isize - b2 as isize + 1)
        } else {
            pp_int(p, l2 as isize);
            ps(p, ":");
            pp_int(p, o2 as isize - b2 as isize + 1);
        }
        ps(p, "]")
    }
}

/// `Format.asprintf "%a" Pos.pp pos`
pub fn show_pos(pos: &oxidized::pos::Pos) -> String {
    format::asprintf(|fmt| {
        let unit = |_: &mut Formatter, _: &()| ();
        let mut p = P::new(fmt, &unit, &unit);
        pp_pos_t(&mut p, pos)
    })
}

/// `Local_id.pp`: the name of an unscoped identifier, else the derived
/// printer of the pair.
pub fn pp_local_id_t<Ex, En>(p: &mut P<'_, Ex, En>, x: &oxidized::local_id::LocalId) {
    let (i, name) = x;
    if *i == 0 {
        ps(p, name)
    } else {
        fprintf_open_tuple(p);
        pp_int(p, *i);
        comma_space(p);
        pp_string(p, name);
        fprintf_close_tuple(p);
    }
}

/// `File_info.pp_mode` (the hand-written one, without the path).
pub fn pp_file_info_mode<Ex, En>(p: &mut P<'_, Ex, En>, mode: &oxidized::file_info::Mode) {
    ps(
        p,
        match mode {
            oxidized::file_info::Mode::Mhhi => "Mhhi",
            oxidized::file_info::Mode::Mstrict => "Mstrict",
        },
    )
}

/// `Namespace_env.pp_mode` (derived, with the path)
fn pp_namespace_env_mode<Ex, En>(p: &mut P<'_, Ex, En>, mode: &oxidized::namespace_env::Mode) {
    ps(
        p,
        match mode {
            oxidized::namespace_env::Mode::ForTypecheck => "Namespace_env.ForTypecheck",
            oxidized::namespace_env::Mode::ForCodegen => "Namespace_env.ForCodegen",
        },
    )
}

/// `Namespace_env.pp_env` (derived, with the path; the maps are
/// `[@opaque]`)
pub fn pp_namespace_env<Ex, En>(p: &mut P<'_, Ex, En>, x: &oxidized::namespace_env::Env) {
    open_box(p, 2);
    ps(p, "{ ");
    field_open(p, "Namespace_env.ns_ns_uses");
    ps(p, "<opaque>");
    close_box(p);
    semi_space(p);
    field_open(p, "ns_class_uses");
    ps(p, "<opaque>");
    close_box(p);
    semi_space(p);
    field_open(p, "ns_fun_uses");
    ps(p, "<opaque>");
    close_box(p);
    semi_space(p);
    field_open(p, "ns_const_uses");
    ps(p, "<opaque>");
    close_box(p);
    semi_space(p);
    field_open(p, "ns_name");
    match &x.name {
        None => ps(p, "None"),
        Some(x) => {
            ps(p, "(Some ");
            pp_string(p, x);
            ps(p, ")");
        }
    }
    close_box(p);
    semi_space(p);
    field_open(p, "ns_mode");
    pp_namespace_env_mode(p, &x.mode);
    close_box(p);
    semi_space(p);
    field_open(p, "ns_disable_xhp_element_mangling");
    pp_bool(p, x.disable_xhp_element_mangling);
    close_box(p);
    space(p);
    ps(p, "}");
    close_box(p);
}

