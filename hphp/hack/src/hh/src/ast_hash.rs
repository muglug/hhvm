//! The `[@@deriving hash]` folders of the AST: the `hash_fold_*` functions
//! that ppx_hash writes for the types of `Ast_defs` and `Aast_defs`
//! (`Aast.hash_fold_def` is `Aast_defs.hash_fold_def`), over the `oxidized`
//! types, folding into Base's hash state (`Ppx_hash_lib.Std.Hash`, Base's
//! "internalhash": OCaml's MurmurHash3-based `caml_hash_mix_*`) as the OCaml
//! does, so that a hash is the OCaml's. See `hh/PORTING.md`.
//!
//! The modules [`ast_defs`] and [`aast_defs`] are generated by
//! `ast_hash_gen.py` (next to this file) from the OCaml type declarations
//! and the `oxidized` declarations, as `ast_show_gen.py` generates
//! `ast_show.rs`. Do not edit them by hand: regenerate (the command is in the
//! generator's header) and replace everything after the generated-code
//! marker line.
//!
//! The folders of the types of other modules that the AST contains are here,
//! by hand: `Pos.hash_fold_t` (with `Relative_path.hash_fold_t`),
//! `Local_id.hash_fold_t`, `File_info.hash_fold_mode`,
//! `Namespace_env.hash_fold_env` (with `S_map.hash_fold_t`).
//!
//! The polymorphic folders of OCaml (`hash_fold_expr _hash_fold_ex
//! _hash_fold_en hsv e`) take the folders of the annotations; here they are
//! in [`H`], with the state.

#![allow(non_snake_case)]

use std::os::unix::ffi::OsStrExt;

/// `Hash.state` (an OCaml int holding the 32-bit state of the internal
/// hash), and the folders of the annotations (`_hash_fold_ex`,
/// `_hash_fold_en`) that every folder passes on.
pub struct H<Ex, En> {
    pub s: u32,
    pub ex: fn(&mut H<Ex, En>, &Ex),
    pub en: fn(&mut H<Ex, En>, &En),
}

impl<Ex, En> H<Ex, En> {
    /// `Hash.create ()`: the seed is 0.
    pub fn create(ex: fn(&mut H<Ex, En>, &Ex), en: fn(&mut H<Ex, En>, &En)) -> Self {
        H { s: 0, ex, en }
    }
}

// The C stubs of Base's internal hash (`internalhash_stubs.c`), which use
// the mixing functions of OCaml's runtime (`hash.c`).

#[inline]
fn mix(h: u32, d: u32) -> u32 {
    let mut d = d.wrapping_mul(0xcc9e2d51);
    d = d.rotate_left(15);
    d = d.wrapping_mul(0x1b873593);
    let mut h = h ^ d;
    h = h.rotate_left(13);
    h.wrapping_mul(5).wrapping_add(0xe6546b64)
}

/// `Hash.fold_int` (`caml_hash_mix_intnat` of a 64-bit int: the low and the
/// high 32 bits mixed so that a small int hashes as a 32-bit one).
#[inline]
pub fn fold_int(s: &mut u32, d: i64) {
    let n = ((d >> 32) ^ (d >> 63) ^ d) as u32;
    *s = mix(*s, n)
}

/// `Hash.fold_string` (`Base_internalhash_fold_blob`: 32-bit little-endian
/// blocks, then up to 3 bytes, then the length).
pub fn fold_string(s: &mut u32, b: &[u8]) {
    let mut h = *s;
    let len = b.len();
    let mut i = 0;
    while i + 4 <= len {
        let w = u32::from_le_bytes([b[i], b[i + 1], b[i + 2], b[i + 3]]);
        h = mix(h, w);
        i += 4;
    }
    let mut w: u32 = 0;
    match len & 3 {
        3 => {
            w = (b[i + 2] as u32) << 16;
            w |= (b[i + 1] as u32) << 8;
            w |= b[i] as u32;
            h = mix(h, w);
        }
        2 => {
            w |= (b[i + 1] as u32) << 8;
            w |= b[i] as u32;
            h = mix(h, w);
        }
        1 => {
            w |= b[i] as u32;
            h = mix(h, w);
        }
        _ => {}
    }
    h ^= len as u32;
    *s = h
}

/// `hash_fold_string` of the bytes of a `String`, a `BString` or a
/// `Vec<u8>`.
#[inline]
pub fn fold_bytes(s: &mut u32, b: &(impl AsRef<[u8]> + ?Sized)) {
    fold_string(s, b.as_ref())
}

/// `Hash.fold_float` (`caml_hash_mix_double`: NaNs and -0.0 normalized).
pub fn fold_float(s: &mut u32, d: f64) {
    let bits = d.to_bits();
    let (mut h, mut l) = ((bits >> 32) as u32, bits as u32);
    if (h & 0x7FF00000) == 0x7FF00000 && (l | (h & 0xFFFFF)) != 0 {
        h = 0x7FF00000;
        l = 0x00000001;
    } else if h == 0x80000000 && l == 0 {
        h = 0;
    }
    *s = mix(mix(*s, l), h)
}

/// `Hash.get_hash_value` (`Base_internalhash_get_hash_value`: the final mix,
/// 30 bits).
pub fn get_hash_value(s: u32) -> isize {
    let mut h = s;
    h ^= h >> 16;
    h = h.wrapping_mul(0x85ebca6b);
    h ^= h >> 13;
    h = h.wrapping_mul(0xc2b2ae35);
    h ^= h >> 16;
    (h & 0x3FFFFFFF) as isize
}

/// `hash_fold_list f`: the length, then the elements.
pub fn fold_list<A>(s: &mut u32, l: &[A], mut f: impl FnMut(&mut u32, &A)) {
    fold_int(s, l.len() as i64);
    for x in l {
        f(s, x)
    }
}

/// `hash_fold_option f`: 0, or 1 then the value.
pub fn fold_option<A>(s: &mut u32, o: Option<&A>, f: impl FnOnce(&mut u32, &A)) {
    match o {
        None => fold_int(s, 0),
        Some(x) => {
            fold_int(s, 1);
            f(s, x)
        }
    }
}

/// `hash_fold_bool`
#[inline]
pub fn fold_bool(s: &mut u32, b: bool) {
    fold_int(s, if b { 1 } else { 0 })
}

/// `S_map.hash_fold_t f` (`Wrapped_map.make_hash_fold_t`): the list of the
/// bindings, in the order of the keys, each as a pair.
pub fn fold_s_map<'a, A: 'a>(
    s: &mut u32,
    map: impl ExactSizeIterator<Item = (&'a String, &'a A)>,
    mut f: impl FnMut(&mut u32, &A),
) {
    fold_int(s, map.len() as i64);
    for (k, v) in map {
        fold_string(s, k.as_bytes());
        f(s, v)
    }
}

/// An OCaml int of 63 bits held in the low bits of a `u64`, sign-extended
/// (what OCaml's `int` holds: the packed positions use all 63 bits).
#[inline]
fn ocaml_int_of_63_bits(bits: u64) -> i64 {
    ((bits << 1) as i64) >> 1
}

// The packed representations of `Pos_span_tiny` and `File_pos_small` (the
// `pos` crate keeps them private): `Pos_span_tiny.make` with 21 bits for the
// beginning of the line, 16 for the line, 20 for the column, none for the
// increments of the two (a tiny span is on one line), 6 for the width;
// `File_pos_small`: 30 bits for the beginning of the line, 24 for the line,
// 9 for the column.

/// `Pos_span_tiny.t` as the OCaml int (`-1` is the dummy span).
fn pos_span_tiny_bits(
    start: &oxidized::file_pos_large::FilePosLarge,
    end: &oxidized::file_pos_large::FilePosLarge,
) -> i64 {
    if start.is_dummy() || end.is_dummy() {
        return -1;
    }
    let (line, bol, offset) = start.line_beg_offset();
    let col = (offset - bol) as u64;
    let width = (end.line_beg_offset().2 - offset) as u64;
    ocaml_int_of_63_bits(((bol as u64) << 42) | ((line as u64) << 26) | (col << 6) | width)
}

/// `File_pos_small.t` as the OCaml int (`-1` is the dummy position).
fn file_pos_small_bits(p: &oxidized::file_pos_large::FilePosLarge) -> i64 {
    if p.is_dummy() {
        return -1;
    }
    let (line, bol, offset) = p.line_beg_offset();
    ocaml_int_of_63_bits(((bol as u64) << 33) + ((line as u64) << 9) + ((offset - bol) as u64))
}

/// `Relative_path.hash_fold_t`: the prefix (`Root`, `Hhi`, `Dummy`, `Tmp`:
/// its index), then the suffix.
pub fn fold_relative_path(s: &mut u32, p: &relative_path::RelativePath) {
    fold_int(
        s,
        match p.prefix() {
            relative_path::Prefix::Root => 0,
            relative_path::Prefix::Hhi => 1,
            relative_path::Prefix::Dummy => 2,
            relative_path::Prefix::Tmp => 3,
        },
    );
    fold_string(s, p.path().as_os_str().as_bytes())
}

/// `Pos.hash_fold_t` (`hash_fold_pos Relative_path.hash_fold_t`): the
/// constructor of the representation the OCaml holds the position in
/// (`Pos_small` 0, `Pos_large` 1, `Pos_tiny` 2), the file, then the packed
/// span or the two file positions. A position is held in the smallest
/// representation that fits it, as `Pos.make` (`compress`) and the parser
/// make them.
pub fn fold_pos(s: &mut u32, pos: &oxidized::pos::Pos) {
    let span = pos.to_raw_span();
    let file = pos.filename();
    if pos.as_tiny_span().is_some() {
        fold_int(s, 2);
        fold_relative_path(s, file);
        fold_int(s, pos_span_tiny_bits(&span.start, &span.end));
    } else {
        let small = |p: &oxidized::file_pos_large::FilePosLarge| {
            let (lnum, bol, offset) = p.line_beg_offset();
            oxidized::file_pos_small::FilePosSmall::from_lnum_bol_offset(lnum, bol, offset)
                .is_some()
        };
        if small(&span.start) && small(&span.end) {
            fold_int(s, 0);
            fold_relative_path(s, file);
            fold_int(s, file_pos_small_bits(&span.start));
            fold_int(s, file_pos_small_bits(&span.end));
        } else {
            fold_int(s, 1);
            fold_relative_path(s, file);
            // `File_pos_large.hash_fold_t`: the record `{ pos_lnum; pos_bol;
            // pos_offset }`.
            for p in [&span.start, &span.end] {
                let (lnum, bol, offset) = p.line_beg_offset();
                fold_int(s, lnum as i64);
                fold_int(s, bol as i64);
                fold_int(s, offset as i64);
            }
        }
    }
}

/// `Pos.hash_fold_t`, as the generated folders call it.
pub fn hash_fold_pos_t<Ex, En>(h: &mut H<Ex, En>, pos: &oxidized::pos::Pos) {
    fold_pos(&mut h.s, pos)
}

/// `Local_id.hash_fold_t`: the pair `(int, string)`.
pub fn hash_fold_local_id_t<Ex, En>(h: &mut H<Ex, En>, x: &oxidized::local_id::LocalId) {
    let (i, name) = x;
    fold_int(&mut h.s, *i as i64);
    fold_string(&mut h.s, name.as_bytes())
}

/// `File_info.hash_fold_mode`
pub fn hash_fold_file_info_mode<Ex, En>(h: &mut H<Ex, En>, mode: &oxidized::file_info::Mode) {
    fold_int(
        &mut h.s,
        match mode {
            oxidized::file_info::Mode::Mhhi => 0,
            oxidized::file_info::Mode::Mstrict => 1,
        },
    )
}

/// `Namespace_env.hash_fold_env`
pub fn hash_fold_namespace_env<Ex, En>(h: &mut H<Ex, En>, x: &oxidized::namespace_env::Env) {
    let s = &mut h.s;
    for map in [&x.ns_uses, &x.class_uses, &x.fun_uses, &x.const_uses] {
        fold_s_map(s, map.iter(), |s, v| fold_string(s, v.as_bytes()));
    }
    fold_option(s, x.name.as_ref(), |s, n| fold_string(s, n.as_bytes()));
    fold_int(
        s,
        match x.mode {
            oxidized::namespace_env::Mode::ForTypecheck => 0,
            oxidized::namespace_env::Mode::ForCodegen => 1,
        },
    );
    fold_bool(s, x.disable_xhp_element_mangling)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hash_string(s: &str) -> isize {
        let mut h = 0;
        fold_string(&mut h, s.as_bytes());
        get_hash_value(h)
    }

    fn hash_int(i: i64) -> isize {
        let mut h = 0;
        fold_int(&mut h, i);
        get_hash_value(h)
    }

    /// The mixing of Base's internal hash (`internalhash_stubs.c`).
    #[test]
    fn internalhash() {
        assert_eq!(get_hash_value(0), 0);
        assert_ne!(hash_string("a"), hash_string("b"));
        assert_ne!(hash_int(-1), hash_int(1));
        // A small negative int hashes as its 32-bit value.
        let mut a = 0;
        fold_int(&mut a, -1);
        assert_eq!(a, mix(0, 0xFFFF_FFFF));
        // The 3 trailing bytes, then the length.
        let mut b = 0;
        fold_string(&mut b, b"abcde");
        let w = u32::from_le_bytes(*b"abcd");
        assert_eq!(b, mix(mix(0, w), b'e' as u32) ^ 5);
    }
}

