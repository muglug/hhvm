//! Port of `refactor_sd/refactor_sd_types.ml`.

use std::collections::BTreeMap;

use crate::pos::Pos;
use crate::tast_env;
use crate::typing_continuations as cont;

pub type LMap<V> = BTreeMap<oxidized::local_id::LocalId, V>;
pub type KMap<V> = BTreeMap<cont::T, V>;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum AnalysisMode {
    /// Flag all possible targets without performing any analysis
    FlagTargets,
    /// Dump constraints generated by analysing the program
    DumpConstraints,
    /// Partially solve key constraints within functions and methods and
    /// report back whether a function is ever upcasted to dynamic.
    SimplifyConstraints,
    /// Globally solve the key constraints and report back whether a
    /// function is ever upcasted to dynamic
    SolveConstraints,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RefactorMode {
    /// Locate upcasts of a specific Class
    Class,
    /// Locate upcasts of a specific Function
    Function,
    /// Locate upcasts of a specific Method
    Method,
}

#[derive(Clone, Copy, Debug)]
pub struct Options {
    pub analysis_mode: AnalysisMode,
    pub refactor_mode: RefactorMode,
}

/// Information about the class or function or method of interest, so that
/// we can limit our reports to the upcasts of that specific element.
/// Class name is only used if the refactor mode is Method.
pub struct ElementInfo {
    pub element_name: String,
}

/// `[@@deriving eq, ord]`
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Entity_ {
    Literal(Pos),
    Variable(isize),
}

pub type Entity = Option<Entity_>;

/// Relationship with shape_analysis: constraint_ constructors are
/// different
#[derive(Clone, Debug)]
pub enum Constraint_ {
    /// Records introduction of an instance of function pointer
    Introduction(Pos),
    /// Records existance and position of upcast dynamic
    Upcast(Entity_, Pos),
    /// Records that the first entity is assigned to the second
    Subset(Entity_, Entity_),
    /// Records that the entity_ was a function pointer that was called
    Called(Pos),
}

/// Relationship with shape_analysis: shape_result
#[derive(Clone, Debug)]
pub enum RefactorSdResult {
    ExistsUpcast(Pos),
    NoUpcast,
}

/// Local variable environment. Its values are `entity`, i.e., `entity_
/// option`, so that we can avoid pattern matching in constraint
/// extraction.
pub type Lenv = KMap<LMap<Entity>>;

#[derive(Clone)]
pub struct Env {
    pub constraints: Vec<Constraint_>,
    pub lenv: Lenv,
    pub tast_env: tast_env::Env,
}

/// `raise (Refactor_sd_exn msg)`
pub fn refactor_sd_exn(msg: String) -> ! {
    panic!("Refactor_sd_types.Refactor_sd_exn({:?})", msg)
}
