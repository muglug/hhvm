//! Port of `utils/ignore/files_to_ignore.stubs.ml` (the open-source
//! `Files_to_ignore`). See `hh/PORTING.md`. The watch specifications (from
//! `hg_dirname` on) were added for the file watchers.
//!
//! The paths to ignore are global state of the process, as in OCaml. They are
//! `Str` regular expressions there; here they are `regex::Regex`es (see
//! `crate::files::ignored_path_regexes`, which translates the `ignored_paths`
//! of a `.hhconfig`), and `Str.string_match p path 0` is a match that starts
//! at the start of the path.

use std::sync::RwLock;

use regex::Regex;

#[allow(non_upper_case_globals)]
static paths_to_ignore: RwLock<Vec<Regex>> = RwLock::new(Vec::new());

pub fn get_paths_to_ignore() -> Vec<Regex> {
    paths_to_ignore.read().unwrap().clone()
}

pub fn set_paths_to_ignore(x: Vec<Regex>) {
    *paths_to_ignore.write().unwrap() = x
}

pub fn ignore_path(regexp: Regex) {
    // `paths_to_ignore := regexp :: !paths_to_ignore`
    paths_to_ignore.write().unwrap().insert(0, regexp)
}

/// `Str.string_match p path 0`
fn string_match(p: &Regex, path: &str) -> bool {
    p.find(path).is_some_and(|m| m.start() == 0)
}

pub fn should_ignore(path: &str) -> bool {
    paths_to_ignore
        .read()
        .unwrap()
        .iter()
        .any(|p| string_match(p, path))
        // ignore shell script wrappers generated by Composer (PHP package manager)
        || path.starts_with("vendor/bin/")
}

use crate::hh_json_helpers::adhoc_json_helpers as j;
use crate::yojson::safe as yojson;

pub fn hg_dirname() -> yojson::T {
    j::strlist(&["dirname", ".hg"])
}

pub fn git_dirname() -> yojson::T {
    j::strlist(&["dirname", ".git"])
}

pub fn svn_dirname() -> yojson::T {
    j::strlist(&["dirname", ".svn"])
}

/// `watch_spec`
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct WatchSpec {
    pub include_extensions: Vec<String>,
    pub include_file_names: Vec<String>,
}

pub fn server_watch_spec() -> WatchSpec {
    WatchSpec {
        include_extensions: [
            "php",
            "phpt",
            "hack",
            "hackpartial",
            "hck",
            "hh",
            "hhi",
            "xhp",
        ]
        .iter()
        .map(|s| s.to_string())
        .collect(),
        include_file_names: [".hhconfig", "PACKAGES.toml"]
            .iter()
            .map(|s| s.to_string())
            .collect(),
    }
}

pub fn watchman_server_expression_terms() -> Vec<yojson::T> {
    vec![
        j::strlist(&["type", "f"]),
        j::pred(
            "anyof",
            vec![
                j::strlist(&["name", ".hhconfig"]),
                j::pred(
                    "anyof",
                    vec![
                        j::strlist(&["suffix", "php"]),
                        j::strlist(&["suffix", "phpt"]),
                        j::strlist(&["suffix", "hack"]),
                        j::strlist(&["suffix", "hackpartial"]),
                        j::strlist(&["suffix", "hck"]),
                        j::strlist(&["suffix", "hh"]),
                        j::strlist(&["suffix", "hhi"]),
                        j::strlist(&["suffix", "xhp"]),
                    ],
                ),
            ],
        ),
        j::pred(
            "not",
            vec![j::pred(
                "anyof",
                vec![hg_dirname(), git_dirname(), svn_dirname()],
            )],
        ),
    ]
}

pub fn watchman_watcher_expression_terms() -> Vec<yojson::T> {
    vec![
        j::strlist(&["type", "f"]),
        j::strlist(&["name", "updatestate"]),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vendor_bin() {
        // No test sets the paths to ignore: they belong to the process.
        assert!(should_ignore("vendor/bin/phpunit"));
        assert!(!should_ignore("src/vendor/bin/phpunit"));
        assert!(!should_ignore("a.php"));
    }

    #[test]
    fn matches_at_the_start() {
        let re = Regex::new("b/c").unwrap();
        assert!(string_match(&re, "b/c/d.php"));
        assert!(!string_match(&re, "a/b/c/d.php"));
    }

    #[test]
    fn watchman_terms() {
        let terms: Vec<String> = watchman_server_expression_terms()
            .iter()
            .map(yojson::to_string)
            .collect();
        assert_eq!(
            terms,
            vec![
                r#"["type","f"]"#.to_string(),
                r#"["anyof",["name",".hhconfig"],["anyof",["suffix","php"],["suffix","phpt"],["suffix","hack"],["suffix","hackpartial"],["suffix","hck"],["suffix","hh"],["suffix","hhi"],["suffix","xhp"]]]"#.to_string(),
                r#"["not",["anyof",["dirname",".hg"],["dirname",".git"],["dirname",".svn"]]]"#.to_string(),
            ]
        );
        assert_eq!(server_watch_spec().include_file_names, vec![".hhconfig", "PACKAGES.toml"]);
    }
}
