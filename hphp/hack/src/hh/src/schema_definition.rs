//! Port of `parser/schema/schema_definition.ml`: the types and the `schema`
//! list (the table of the full-fidelity syntax kinds, in the OCaml's order).
//! See `hh/PORTING.md`.
//!
//! The list was translated mechanically from the OCaml source (record by
//! record, field by field). The functions of the module that follow the list
//! (`generated_aggregate_types`, `aggregation_of`, `aggregate_type_name`,
//! `string_of_child_spec`, ...) are not ported yet: nothing calls them.

