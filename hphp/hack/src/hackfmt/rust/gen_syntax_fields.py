"""Generate src/syntax_fields.rs from the parser's generated syntax variants.

Usage: python3 gen_syntax_fields.py > src/syntax_fields.rs

hackfmt's tree is untyped (a kind and a list of children, like the OCaml
editable syntax). This gives each syntax kind a struct of named references to
its children, in the order of the full-fidelity schema, so that the transform
can name fields the way hack_format.ml does.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(
    HERE, "..", "..", "parser", "syntax_by_ref", "syntax_variant_generated.rs"
)


def snake(name):
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "_", name).lower()


def main():
    text = open(SRC).read()
    structs = re.findall(
        r"pub struct (\w+)Children<'a, T, V> \{(.*?)\n\}", text, re.S
    )
    out = []
    out.append("// @" + "generated by gen_syntax_fields.py from")
    out.append("// parser/syntax_by_ref/syntax_variant_generated.rs. Do not edit.")
    out.append("")
    out.append("#![allow(dead_code)]")
    out.append("")
    out.append("use parser_core_types::syntax_kind::SyntaxKind;")
    out.append("")
    out.append("use crate::syntax::Node;")
    out.append("")
    counts = []
    for name, body in structs:
        fields = re.findall(r"pub (\w+): Syntax<'a, T, V>", body)
        counts.append((name, len(fields)))
        out.append("pub struct %s<'n, 'a> {" % name)
        for f in fields:
            out.append("    pub %s: &'n Node<'a>," % f)
        out.append("}")
        out.append("")
        out.append("pub fn %s<'n, 'a>(n: &'n Node<'a>) -> %s<'n, 'a> {" % (snake(name), name))
        out.append("    debug_assert_eq!(n.kind, SyntaxKind::%s);" % name)
        out.append("    let c = &n.children;")
        out.append("    %s {" % name)
        for i, f in enumerate(fields):
            out.append("        %s: &c[%d]," % (f, i))
        out.append("    }")
        out.append("}")
        out.append("")
    out.append("/// The number of children of a node of the given kind, if it has fields.")
    out.append("pub fn field_count(kind: SyntaxKind) -> Option<usize> {")
    out.append("    match kind {")
    for name, n in counts:
        out.append("        SyntaxKind::%s => Some(%d)," % (name, n))
    out.append("        _ => None,")
    out.append("    }")
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
